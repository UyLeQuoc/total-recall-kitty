import { loadEnv, withoutBlanks } from "@total-recall/memory";
import { z } from "zod";

const flag = z.enum(["on", "off"]).default("off");

/**
 * Kitty reads the repo's `.env` as is, plus the keys its setup script generated (ADR-0062). Money and
 * Move are on testnet; memory is the operator's account on the mainnet relayer, under `kitty:*`.
 */
export const envSchema = z.object({
  DATABASE_URL: z.string().default("postgres://kitty:kitty@localhost:5436/kitty"),
  KITTY_PORT: z.coerce.number().int().default(8821),
  KITTY_BASE_URL: z.string().default("http://localhost:8821"),
  KITTY_WORKER: flag,
  KITTY_BOT: flag,
  /** Seconds between keeper passes. */
  KITTY_KEEPER_SECONDS: z.coerce.number().positive().default(60),
  KITTY_PACKAGE_ID: z.string().optional(),
  /** The spender of every member's allowance. Generated by scripts/setup-testnet.ts. */
  KITTY_KEEPER_KEY: z.string().optional(),
  /** Test members' keys, comma-separated (labelled "test" everywhere). */
  KITTY_MEMBER_KEYS: z.string().optional(),
  USDC_COIN_TYPE_TESTNET: z
    .string()
    .default("0xa1ec7fc00a6f40db9693ad1415d0c193ad3906494428cf252621037bd7117e29::usdc::USDC"),
  TATUM_API_KEY_TESTNET: z.string().optional(),
  TATUM_SUI_GRPC_TESTNET: z.string().optional(),
  /** Pays gas for every Kitty transaction; never a member. */
  SPONSOR_PRIVATE_KEY_TESTNET: z.string().optional(),
  MEMWAL_ACCOUNT_ID: z.string().optional(),
  MEMWAL_PRIVATE_KEY: z.string().optional(),
  MEMWAL_SERVER_URL: z.string().default("https://relayer.memory.walrus.xyz"),
  TELEGRAM_BOT_TOKEN: z.string().optional(),
});
export type Env = z.infer<typeof envSchema>;

export function readEnv(): Env {
  loadEnv();
  return envSchema.parse(withoutBlanks(process.env));
}
