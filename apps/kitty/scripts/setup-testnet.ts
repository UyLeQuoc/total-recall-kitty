// KT2 (ADR-0062): generates Kitty's testnet keeper key and three test members' keys into the repo's
// `.env`, once. Values are never printed; only the addresses are.
//   bun scripts/setup-testnet.ts
import { appendFileSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Ed25519Keypair } from "@mysten/sui/keypairs/ed25519";
import { keypairFrom } from "../src/keys.ts";

const envPath = join(dirname(fileURLToPath(import.meta.url)), "../../../.env");
const text = readFileSync(envPath, "utf8");
const has = (name: string) => new RegExp(`^${name}=.+`, "m").test(text);
const lines: string[] = [];
if (!has("KITTY_KEEPER_KEY"))
  lines.push(`KITTY_KEEPER_KEY=${Ed25519Keypair.generate().getSecretKey()}`);
if (!has("KITTY_MEMBER_KEYS")) {
  lines.push(
    `KITTY_MEMBER_KEYS=${[0, 1, 2].map(() => Ed25519Keypair.generate().getSecretKey()).join(",")}`,
  );
}
if (lines.length)
  appendFileSync(
    envPath,
    `\n# Kitty (U11, ADR-0062): testnet keeper and test members, generated by apps/kitty/scripts/setup-testnet.ts\n${lines.join("\n")}\n`,
  );

const after = readFileSync(envPath, "utf8");
const value = (name: string) => new RegExp(`^${name}=(.+)$`, "m").exec(after)?.[1];
console.log("keeper", keypairFrom(value("KITTY_KEEPER_KEY"), "KITTY_KEEPER_KEY").toSuiAddress());
for (const [i, k] of (value("KITTY_MEMBER_KEYS") ?? "").split(",").entries()) {
  console.log(`member ${i}`, keypairFrom(k, "KITTY_MEMBER_KEYS").toSuiAddress());
}
console.log(lines.length ? "generated" : "already set");
